#!/usr/bin/env python3
"""Import the MIDI Guide dataset (https://midi.guide, github.com/pencilresearch/midi) for the Synth CC mapper.

    git clone --depth 1 https://github.com/pencilresearch/midi.git /path/to/midi-guide
    python3 -I tools/import_midiguide.py /path/to/midi-guide > src/1d-midiguide.js

The dataset is CC BY-SA 4.0 (see its LICENSE); src/1d-midiguide.js is an adaptation and stays under that license.
Every CC/NRPN row of every device CSV is kept (*.triggers.csv note maps are not used). Each row is classified:
  cc    single 7-bit CC 0-119, no LSB            -> a KeyStep Pro knob can send it
  cc14  CC with an LSB (14-bit pair)             -> not offered (a knob sends one 7-bit CC)
  mode  CC 120-127 (channel mode messages)       -> not offered
  nrpn  NRPN only                                -> not offered
  other no CC or NRPN (SysEx, program change, ...) or an unreadable CC field
The catalog is gzip + base64 inside the page so it opens straight from disk; the page unpacks it on first use.
"""
import base64, csv, gzip, json, subprocess, sys
from datetime import date
from pathlib import Path

COLS = ['manufacturer', 'device', 'section', 'parameter_name', 'parameter_description', 'cc_msb', 'cc_lsb',
        'cc_min_value', 'cc_max_value', 'cc_default_value', 'nrpn_msb', 'nrpn_lsb', 'nrpn_min_value',
        'nrpn_max_value', 'nrpn_default_value', 'orientation', 'notes', 'usage']


def num(s, hi):
    s = (s or '').strip()
    return int(s) if s.isdigit() and int(s) <= hi else None


def kind(r):
    raw_cc, raw_lsb = r['cc_msb'].strip(), r['cc_lsb'].strip()
    cc, lsb = num(raw_cc, 127), num(raw_lsb, 127)
    if raw_cc and cc is None:
        return 'other'
    if cc is not None:
        if raw_lsb:
            return 'cc14'
        return 'mode' if cc >= 120 else 'cc'
    if r['nrpn_msb'].strip() or r['nrpn_lsb'].strip():
        return 'nrpn'
    return 'other'


def main(root):
    root = Path(root)
    rev = subprocess.run(['git', '-C', str(root), 'log', '-1', '--format=%H %cs'], capture_output=True, text=True).stdout.split()
    devices, counts = [], {'cc': 0, 'cc14': 0, 'mode': 0, 'nrpn': 0, 'other': 0}
    for f in sorted(root.glob('*/*.csv'), key=lambda p: (p.parent.name.lower(), p.stem.lower())):
        if f.name.endswith('.triggers.csv'):
            continue
        with f.open(newline='', encoding='utf-8-sig') as fh:
            rd = csv.DictReader(fh)
            if rd.fieldnames != COLS:
                sys.exit(f'{f}: unexpected columns {rd.fieldnames}')
            rows = list(rd)
        sections, params = [], []
        for r in rows:
            r = {k: (v or '').strip() for k, v in r.items()}
            k = kind(r)
            counts[k] += 1
            if r['section'] not in sections:
                sections.append(r['section'])
            # [section, name, description, kind, cc, lsb, nrpn msb, nrpn lsb, cc min, cc max, cc default,
            #  nrpn min, nrpn max, nrpn default, centered, notes, usage, raw cc text when unreadable]
            p = [sections.index(r['section']), r['parameter_name'], r['parameter_description'], k,
                 num(r['cc_msb'], 127), num(r['cc_lsb'], 127), num(r['nrpn_msb'], 127), num(r['nrpn_lsb'], 127),
                 num(r['cc_min_value'], 127), num(r['cc_max_value'], 127), num(r['cc_default_value'], 127),
                 num(r['nrpn_min_value'], 16383), num(r['nrpn_max_value'], 16383), num(r['nrpn_default_value'], 16383),
                 1 if r['orientation'] == 'centered' else 0, r['notes'], r['usage'],
                 r['cc_msb'] if k == 'other' and r['cc_msb'] else '']
            while p and p[-1] in ('', None):
                p.pop()
            params.append(p)
        devices.append({'m': f.parent.name, 'd': f.stem, 's': sections, 'p': params})
    data = {'source': 'MIDI Guide by Pencil Research, https://midi.guide (github.com/pencilresearch/midi)',
            'license': 'CC BY-SA 4.0, https://creativecommons.org/licenses/by-sa/4.0/',
            'note': "The portions of this dataset that refer to specific devices may be owned by the devices' respective manufacturers.",
            'revision': rev[0] if rev else 'unknown', 'revisionDate': rev[1] if len(rev) > 1 else '',
            'retrieved': date.today().isoformat(), 'counts': counts, 'devices': devices}
    blob = base64.b64encode(gzip.compress(json.dumps(data, separators=(',', ':'), ensure_ascii=False).encode(), 9, mtime=0)).decode()
    print('/* MIDI Guide catalog for the Synth CC mapper: generated by tools/import_midiguide.py; do not edit.')
    print(f'   Source: MIDI Guide by Pencil Research, https://midi.guide, github.com/pencilresearch/midi @ {data["revision"]} ({data["revisionDate"]}), retrieved {data["retrieved"]}.')
    print('   License: CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/). This file is an adaptation of that dataset')
    print("   (converted to compressed JSON) and is shared under the same license. Device-specific portions may be owned by their manufacturers.")
    print(f'   {len(devices)} devices; rows: {counts}. */')
    print(f'const MIDIGUIDE_META={json.dumps({k: data[k] for k in ("source", "license", "revision", "revisionDate", "retrieved", "counts")}, separators=(",", ":"))};')
    print(f'const MIDIGUIDE_GZ="{blob}";')
    print(f'{len(devices)} devices, {counts}', file=sys.stderr)


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
